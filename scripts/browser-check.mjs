import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const base = process.env.DEMO_TEST_URL || 'http://127.0.0.1:4173';
const localBrowser = fileURLToPath(new URL('../.sites-runtime/browser/chrome-headless-shell-linux64/chrome-headless-shell', import.meta.url));
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'],
  executablePath: process.env.CHROMIUM_EXECUTABLE || (existsSync(localBrowser) ? localBrowser : undefined) });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('test-results', { recursive: true });
const ready = () => page.waitForFunction(() => document.querySelector('#app').getAttribute('aria-busy') === 'false' && document.querySelector('#tracking-canvas').dataset.frameId);
const current = async () => page.locator('#scene-code').innerText();
try {
  await page.goto(base, { waitUntil: 'networkidle' }); await ready();
  assert.equal(await page.locator('.scene-item').count(), 8);
  assert.equal(await current(), 'I_BS_01');
  assert.equal(await page.locator('video').count(), 2);
  assert.equal(await page.locator('#error-banner').isVisible(), false);
  await page.locator('#play-button').click();
  await page.waitForFunction(() => document.querySelector('#raw-video').currentTime > 0.2);
  assert.equal(await page.locator('#app').evaluate(e => e.classList.contains('is-playing')), true);
  await page.locator('#play-button').click();
  await page.locator('#seek').evaluate(el => { el.value = '3.04'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForFunction(() => document.querySelector('#tracking-canvas').dataset.frameId === '77');
  const proof = await page.evaluate(async () => {
    const raw = document.querySelector('#raw-video'), cipher = document.querySelector('#cipher-video');
    const frame = Number(document.querySelector('#tracking-canvas').dataset.frameId) - 1;
    const data = await (await fetch('media/I_BS_01/tracks.json')).json();
    return { actual: document.querySelector('#id-list').dataset.ids, expected: data.frames[frame].map(o => o.id).join(','), drift: Math.abs(raw.currentTime-cipher.currentTime) };
  });
  assert.equal(proof.actual, proof.expected); assert.ok(proof.drift <= 0.12);
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.getByRole('button', { name: '放大跟踪视频', exact: true }).click();
  assert.equal(await page.locator('#viewer').evaluate(e => e.open), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#viewer').evaluate(e => e.open), false);
  await page.locator('#next-button').click(); await ready(); assert.equal(await current(), 'I_BS_02');
  await page.locator('#prev-button').click(); await ready(); assert.equal(await current(), 'I_BS_01');
  await page.locator('#speed').selectOption('2');
  assert.equal(await page.locator('#raw-video').evaluate(e => e.playbackRate), 2);
  await page.locator('#play-button').click();
  await page.locator('#raw-video').evaluate(e => { e.currentTime = e.duration - 0.12; });
  await page.waitForFunction(() => document.querySelector('#scene-code').textContent === 'I_BS_02'); await ready();
  await page.waitForFunction(() => document.querySelector('#app').classList.contains('is-playing'));
  assert.equal(await page.locator('#app').evaluate(e => e.classList.contains('is-playing')), true);
  await page.locator('#play-button').click();
  await page.locator('.auto-next').click();
  assert.equal(await page.locator('#auto-next').isChecked(), false);
  await page.locator('#play-button').click();
  await page.locator('#raw-video').evaluate(e => { e.currentTime = e.duration - 0.12; });
  await page.waitForFunction(() => document.querySelector('#raw-video').ended);
  assert.equal(await current(), 'I_BS_02');
  await page.locator('.auto-next').click();
  assert.equal(await page.locator('#auto-next').isChecked(), true);
  await page.locator('.scene-item').nth(7).click(); await ready(); assert.equal(await current(), 'O_RA_02');
  await page.locator('#play-button').click();
  await page.locator('#raw-video').evaluate(e => { e.currentTime = e.duration - 0.12; });
  await page.waitForFunction(() => document.querySelector('#play-button span').textContent === '重新播放全部');
  await page.locator('#play-button').click();
  await page.waitForFunction(() => document.querySelector('#scene-code').textContent === 'I_BS_01'); await ready();
  if (await page.locator('#app').evaluate(e => e.classList.contains('is-playing'))) await page.locator('#play-button').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(250);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.equal(await page.locator('#play-button').isVisible(), true);
  await page.locator('#inline-play-button').click();
  await page.waitForFunction(() => document.querySelector('#raw-video').currentTime > 0.2);
  await page.locator('#inline-play-button').click();
  await page.locator('#seek').evaluate(el => { el.value = '3.04'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForFunction(() => document.querySelector('#tracking-canvas').dataset.frameId === '77');
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile('test-results/report.json', JSON.stringify({ passed: true, checks: ['ordered playlist', 'actual tracking IDs', 'video sync', 'play/pause', 'seek', 'previous/next', 'playback speed', 'automatic next scene', 'stop without automatic next', 'last-scene stop and restart', 'zoom', 'mobile layout'], desktop: 'desktop.png', mobile: 'mobile.png' }, null, 2));
  process.stdout.write('Browser checks passed: playback, actual IDs, sync, sequence transitions, seeking, zoom and mobile layout\n');
} catch (error) {
  await page.screenshot({ path: 'test-results/failure.png', fullPage: true }).catch(() => {});
  throw error;
} finally { await browser.close(); }
